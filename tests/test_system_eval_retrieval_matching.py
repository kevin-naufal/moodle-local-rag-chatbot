import unittest
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
APP_DIR = PROJECT_ROOT / "app"
if str(APP_DIR) not in sys.path:
    sys.path.insert(0, str(APP_DIR))

from system_eval import evaluate_answer_runs, load_question_specs_from_text


class SystemEvalRetrievalMatchingTest(unittest.TestCase):
    class FakeSemanticCoverageEvaluator:
        def compute_gold_coverage(self, answer, gold_points, gold_point_anchor_terms=None):
            return 1, 0.375, [0.65, 0.2]

    def test_evidence_level_requires_half_of_anchor_groups(self):
        question_specs = load_question_specs_from_text(
            """
            {
              "source_document": "C:\\\\tmp\\\\doc.pdf",
              "scope": "in-scope",
              "questions": [
                {
                  "id": "q1",
                  "question": "Which resources should a program conserve?",
                  "gold_source": ["Section 3.2, PDF page 2"],
                  "gold_point_anchor_terms": [
                    ["storage"],
                    ["traffic"],
                    ["network"],
                    ["disk", "disks"]
                  ]
                }
              ]
            }
            """
        )
        answer_runs = [
            {
                "question_id": "q1",
                "mode": "rag_bert",
                "model_name": "model",
                "run_id": 1,
                "status": "success",
                "model_answer": "It should conserve several resources.",
                "retrieved_context": [
                    {
                        "source": "doc.pdf",
                        "page": 2,
                        "text": "The amount of storage space taken by variables may matter.",
                    },
                    {
                        "source": "doc.pdf",
                        "page": 2,
                        "text": "The amount of traffic generated by a program may matter.",
                    },
                ],
            }
        ]

        evaluated = evaluate_answer_runs(
            answer_runs,
            question_specs,
            top_k=2,
            retrieval_match_level="evidence",
        )

        self.assertEqual(evaluated[0]["source_hit_at_k"], 1)
        self.assertEqual(evaluated[0]["rank_of_gold_source"], 2)
        self.assertEqual(evaluated[0]["mrr"], 0.5)

    def test_evidence_level_misses_when_less_than_half_of_anchor_groups_match(self):
        question_specs = load_question_specs_from_text(
            """
            {
              "source_document": "C:\\\\tmp\\\\doc.pdf",
              "scope": "in-scope",
              "questions": [
                {
                  "id": "q1",
                  "question": "Which resources should a program conserve?",
                  "gold_source": ["Section 3.2, PDF page 2"],
                  "gold_point_anchor_terms": [
                    ["storage"],
                    ["traffic"],
                    ["network"],
                    ["disk", "disks"]
                  ]
                }
              ]
            }
            """
        )
        answer_runs = [
            {
                "question_id": "q1",
                "mode": "rag_bert",
                "model_name": "model",
                "run_id": 1,
                "status": "success",
                "model_answer": "It should conserve several resources.",
                "retrieved_context": [
                    {
                        "source": "doc.pdf",
                        "page": 2,
                        "text": "The amount of storage space taken by variables may matter.",
                    },
                    {
                        "source": "doc.pdf",
                        "page": 2,
                        "text": "Simple algorithms are easier to implement and document.",
                    },
                ],
            }
        ]

        evaluated = evaluate_answer_runs(
            answer_runs,
            question_specs,
            top_k=2,
            retrieval_match_level="evidence",
        )

        self.assertEqual(evaluated[0]["source_hit_at_k"], 0)
        self.assertIsNone(evaluated[0]["rank_of_gold_source"])
        self.assertEqual(evaluated[0]["mrr"], 0.0)

    def test_coverage_at_k_counts_gold_point_anchor_groups_in_top_context(self):
        question_specs = load_question_specs_from_text(
            """
            {
              "source_document": "C:\\\\tmp\\\\doc.pdf",
              "scope": "in-scope",
              "questions": [
                {
                  "id": "q1",
                  "question": "How is a for-statement bounded?",
                  "gold_points": [
                    "The upper bound is O(1 + (f(n) + 1)g(n)).",
                    "The f(n) + 1 factor accounts for the body, test, and reinitialization.",
                    "The leading 1 accounts for initialization and zero iterations.",
                    "The common case simplifies to O(f(n)g(n))."
                  ],
                  "gold_point_anchor_terms": [
                    ["O(1 + (f(n) + 1)g(n))", "upper bound"],
                    ["body", "test", "reinitialization"],
                    ["initialization", "zero iterations"],
                    ["O(f(n)g(n))", "common case"]
                  ]
                }
              ]
            }
            """
        )
        answer_runs = [
            {
                "question_id": "q1",
                "mode": "rag_bert",
                "model_name": "model",
                "run_id": 1,
                "status": "success",
                "model_answer": "The answer is based on retrieved context.",
                "retrieved_context": [
                    {
                        "source": "doc.pdf",
                        "page": 34,
                        "text": "The upper bound is O(1 + (f(n) + 1)g(n)).",
                    },
                    {
                        "source": "doc.pdf",
                        "page": 34,
                        "text": "The factor covers the body, test, and reinitialization.",
                    },
                    {
                        "source": "doc.pdf",
                        "page": 35,
                        "text": "This context is outside top-k and mentions initialization and zero iterations.",
                    },
                ],
            }
        ]

        evaluated = evaluate_answer_runs(answer_runs, question_specs, top_k=2)

        self.assertEqual(evaluated[0]["gold_points_total"], 4)
        self.assertEqual(evaluated[0]["gold_points_covered_at_k"], 2)
        self.assertEqual(evaluated[0]["coverage_at_k"], 0.5)

    def test_semantic_coverage_at_k_uses_gold_point_similarity_against_top_context(self):
        question_specs = load_question_specs_from_text(
            """
            {
              "source_document": "C:\\\\tmp\\\\doc.pdf",
              "scope": "in-scope",
              "questions": [
                {
                  "id": "q1",
                  "question": "What do benchmark inputs represent?",
                  "gold_points": [
                    "Benchmark inputs represent the job mix.",
                    "Performance on benchmark inputs is assumed to indicate performance on all inputs."
                  ],
                  "gold_point_anchor_terms": [
                    ["job mix"],
                    ["all inputs"]
                  ]
                }
              ]
            }
            """
        )
        answer_runs = [
            {
                "question_id": "q1",
                "mode": "rag_msmarco",
                "model_name": "model",
                "run_id": 1,
                "status": "success",
                "model_answer": "The answer is based on retrieved context.",
                "retrieved_context": [
                    {
                        "source": "doc.pdf",
                        "page": 3,
                        "text": "The examples should reflect the workload used to judge programs.",
                    }
                ],
            }
        ]

        evaluated = evaluate_answer_runs(
            answer_runs,
            question_specs,
            top_k=1,
            coverage_evaluator=self.FakeSemanticCoverageEvaluator(),
        )

        self.assertEqual(evaluated[0]["coverage_eval_method"], "semantic_embedding")
        self.assertEqual(evaluated[0]["gold_points_total"], 2)
        self.assertEqual(evaluated[0]["gold_points_covered_at_k"], 1)
        self.assertEqual(evaluated[0]["coverage_at_k"], 0.375)


if __name__ == "__main__":
    unittest.main()
